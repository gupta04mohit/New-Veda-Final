import { Chroma } from "@langchain/community/vectorstores/chroma";
import { OpenAIEmbeddings } from "@langchain/openai";

const researchAgentNode = async (state: AgentState) => {
  let context = "";
  try {
    const embeddings = new OpenAIEmbeddings({ modelName: "text-embedding-3-small" });
    const vectorStore = await Chroma.fromExistingCollection(embeddings, { collectionName: "veda_knowledge" });
    
    const lastMsg = state.messages[state.messages.length - 1].content as string;
    const results = await vectorStore.similaritySearch(lastMsg, 2);
    context = results.map(r => `Source: ${r.metadata.source} - ${r.pageContent}`).join('\n');
  } catch (err) {
    console.error("RAG Error:", err);
  }

  const prompt = new SystemMessage(`You are the Ayurvedic Research Agent. Provide textbook-backed answers.
  
Retrieved Knowledge Context:
${context}

` + getContextPrompt(state));
  return { messages: [await llm.invoke([prompt, ...state.messages])] };
};

import neo4j from "neo4j-driver";

const knowledgeGraphAgentNode = async (state: AgentState) => {
  let graphContext = "";
  try {
    const driver = neo4j.driver(
      process.env.NEO4J_URI || 'neo4j://localhost',
      neo4j.auth.basic(process.env.NEO4J_USER || 'neo4j', process.env.NEO4J_PASSWORD || 'password')
    );
    const session = driver.session();
    
    // In a real system, you'd extract entities (diseases, symptoms) from the user's message
    // For this implementation, we query a general structure based on their dosha profile or symptoms.
    const cypherQuery = `
      MATCH (d:Disease)-[:HAS_SYMPTOM]->(s:Symptom)
      MATCH (d)-[:TREATED_BY]->(h:Herb)
      RETURN d.name as disease, collect(s.name) as symptoms, collect(h.name) as herbs LIMIT 3
    `;
    
    const result = await session.run(cypherQuery);
    graphContext = result.records.map(record => 
      `Disease: ${record.get('disease')} | Symptoms: ${record.get('symptoms').join(',')} | Herbs: ${record.get('herbs').join(',')}`
    ).join('\n');
    
    await session.close();
    await driver.close();
  } catch (err) {
    console.error("Knowledge Graph Error:", err);
  }

  const prompt = new SystemMessage(`You are the Knowledge Graph Agent. Traverse semantic relationships between diseases, herbs, and Doshas to find root causes.
  
Knowledge Graph Context:
${graphContext}

` + getContextPrompt(state));
  return { messages: [await llm.invoke([prompt, ...state.messages])] };
};

