// 1. Define the State Structure
export interface AgentState {
  messages: BaseMessage[];
  nextAgent: string | null;
  doshaProfile: any;
  currentSymptoms: string[];
  healthScore: number;
  userContext?: any;
}

// 2. Initialize LLM
const llm = new ChatOpenAI({
  modelName: "gpt-4-turbo",
  temperature: 0,
});

// 3. Define the Master Orchestrator Node
const orchestratorNode = async (state: AgentState) => {
  console.log("--- MASTER ORCHESTRATOR ---");
  const lastMessage = state.messages[state.messages.length - 1].content;
  
  const systemPrompt = new SystemMessage(
    `You are the Master Orchestrator of VedaAI, an advanced Preventive Healthcare Operating System.
    Based on the user's latest input, route to the most appropriate specialized agents. If a query is complex, you can route to MULTIPLE agents for a debate/synthesis.
    
    Available Agents:
    - "dosha_agent": Body constitution, Vata/Pitta/Kapha.
    - "symptom_agent": Current physical/mental symptoms.
    - "disease_forecast_agent": Predicting disease risks from habits.
    - "longevity_agent": Biological age, life expectancy.
    - "diet_agent": Meal planning.
    - "food_analysis_agent": Scanning food images.
    - "coach_agent": Motivation, habits, sleep.
    - "research_agent": General Ayurvedic texts lookup.
    - "knowledge_graph_agent": Deep root-cause reasoning.
    
    Respond ONLY with a valid JSON array of strings containing the exact names of the agents. Example: ["diet_agent", "dosha_agent"]`
  );

  const response = await llm.invoke([systemPrompt, new HumanMessage(lastMessage as string)]);
  let nextAgent = response.content.toString().trim();
  
  // Clean up potential markdown formatting from LLM
  if (nextAgent.startsWith('```json')) {
    nextAgent = nextAgent.replace(/```json/g, '').replace(/```/g, '').trim();
  } else if (nextAgent.startsWith('```')) {
    nextAgent = nextAgent.replace(/```/g, '').trim();
  }

  console.log(`[Orchestrator] Routing to: ${nextAgent}`);
  return { nextAgent };
};

const masterSynthesizerNode = async (state: AgentState) => {
  console.log("--- MASTER SYNTHESIZER ---");
  
  const prompt = new SystemMessage(`You are the Master Synthesizer Agent.
  Several specialized agents have just analyzed the user's request. 
  Your job is to read their outputs from the recent conversation history and combine them into a single, cohesive, and easy-to-read response for the user.
  Resolve any conflicts between the agents' advice (Agent Debate) gracefully.
  Do not mention the internal agents by name to the user. Just provide the final synthesized advice.`);

  // Get the original user message
  const userMsg = state.messages.find(m => m.getType() === 'human')?.content || "";
  
  return { messages: [await llm.invoke([prompt, new HumanMessage(`User asked: ${userMsg}\n\nSynthesize the AI responses above into one final answer.`)])] };
};

